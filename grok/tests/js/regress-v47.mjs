// Regressão V4.7: toast some sozinho e fica acima da barra de abas; estresse/alimentação por período.
import puppeteer from 'puppeteer-core';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const cfg = path.resolve(here, '../tmp/config.dev.php');
if (!fs.existsSync(cfg)) { console.error('Rode o PHPUnit antes (gera tests/tmp/config.dev.php).'); process.exit(2); }
const shots = process.env.SHOTS || path.resolve(here, '../tmp/v47');
fs.mkdirSync(shots, { recursive: true });
const port = 8800 + Math.floor(Math.random() * 90);
const base = `http://127.0.0.1:${port}`;
const srv = spawn(process.env.PHP_BIN || 'php', ['-S', `127.0.0.1:${port}`, '-t', path.join(root, 'public_html')], { env: { ...process.env, BIPOLAR_CONFIG: cfg }, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
const browser = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
let fail = 0;
const ok = (c, msg) => { console.log(`${c ? '✓' : '✗'} ${msg}`); if (!c) fail++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 412, height: 915, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  page.on('pageerror', (e) => { console.log('pageerror', e.message); fail++; });
  page.on('console', (m) => { if (/Content Security Policy|Refused to apply/i.test(m.text())) { console.log('CSP:', m.text()); fail++; } });
  await page.emulateTimezone('America/Cuiaba');
  await page.goto(`${base}/auth/dev.php?u=v47${Date.now().toString(36)}`, { waitUntil: 'networkidle0' });
  await page.goto(`${base}/?aba=registrar`, { waitUntil: 'networkidle0' });
  const vis = () => page.evaluate(() => { const t = document.querySelector('.toast'); if (!t) return null; const s = getComputedStyle(t); const r = t.getBoundingClientRect(); const n = document.querySelector('nav.tabs').getBoundingClientRect(); return { show: t.classList.contains('show'), visible: s.visibility !== 'hidden' && +s.opacity > 0.05, live: t.getAttribute('aria-live'), text: t.textContent, bottom: r.bottom, navTop: n.top }; });
  const t0 = await vis();
  ok(t0 && !t0.visible && t0.live === 'polite', 'toast existe oculto com aria-live=polite');
  const ready = await page.evaluate(() => { const f = document.getElementById('form-day'); if (!f) return false; f.classList.remove('hidden'); f.querySelectorAll('details[data-per-period]').forEach((d) => { d.hidden = false; d.open = true; }); return true; });
  ok(ready, 'formulário Meu dia presente');
  const setP = (p) => page.evaluate((p) => { const r = document.getElementById('p-' + p); r.checked = true; r.dispatchEvent(new Event('change', { bubbles: true })); }, p);
  const fill = (lv, note, binge) => page.evaluate((lv, note, binge) => { const f = document.getElementById('form-day'); f.querySelector(`input[name=stress_level][value="${lv}"]`).checked = true; f.querySelector(`input[name=food_sweets][value="${lv}"]`).checked = true; f.elements.stress_note.value = note; f.elements.food_binge.checked = binge; }, lv, note, binge);
  const read = () => page.evaluate(() => { const f = document.getElementById('form-day'); const g = (n) => (f.querySelector(`input[name=${n}]:checked`) || {}).value || ''; return { st: g('stress_level'), sw: g('food_sweets'), note: f.elements.stress_note.value, binge: f.elements.food_binge.checked, name: document.querySelector('.day-period-name').textContent }; });
  const submit = () => page.evaluate(() => document.getElementById('form-day').requestSubmit());
  await setP('manha'); await fill('3', 'briga no trabalho', true);
  await submit(); await sleep(700);
  const t1 = await vis();
  ok(t1.visible && /salvo/i.test(t1.text), 'toast "salvo" aparece: ' + t1.text);
  ok(t1.bottom <= t1.navTop + 1, `toast acima da barra de abas (${Math.round(t1.bottom)} ≤ ${Math.round(t1.navTop)})`);
  await page.screenshot({ path: path.join(shots, '01-toast-visivel.png') });
  await sleep(4300);
  const t2 = await vis();
  ok(!t2.visible, 'toast some sozinho após ~4 s');
  await page.screenshot({ path: path.join(shots, '02-toast-sumiu.png') });
  await setP('tarde'); await sleep(500);
  const r1 = await read();
  ok(!r1.st && !r1.sw && r1.note === '' && !r1.binge, 'trocar para Tarde limpa estresse/alimentação');
  ok(/tarde/i.test(r1.name), 'cabeçalho mostra o período: ' + r1.name);
  await page.screenshot({ path: path.join(shots, '03-tarde-vazio.png') });
  await fill('1', 'tranquilo', false); await submit(); await sleep(700);
  await setP('manha'); await sleep(500);
  const r2 = await read();
  ok(r2.st === '3' && r2.sw === '3' && r2.note === 'briga no trabalho' && r2.binge, 'voltar para Manhã recarrega os valores da manhã');
  await page.screenshot({ path: path.join(shots, '04-manha-recarregada.png') });
  await setP('tarde'); await sleep(500);
  const r3 = await read();
  ok(r3.st === '1' && r3.note === 'tranquilo' && !r3.binge, 'Tarde mantém os próprios valores');
  // toast some ao trocar de aba
  await submit(); await sleep(500);
  await page.click('#tab-historico'); await sleep(400);
  ok(!(await vis()).visible, 'toast some ao navegar para outra aba');
  await page.screenshot({ path: path.join(shots, '05-historico.png') });
} catch (e) { console.log('erro', e); fail++; }
await browser.close(); srv.kill();
console.log(fail ? `\nRegressão V4.7: ${fail} falha(s)` : '\nRegressão V4.7 OK');
process.exit(fail ? 1 : 0);
